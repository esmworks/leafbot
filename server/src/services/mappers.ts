export const toRun = (r: Row<typeof schema.routineRuns>): RoutineRun => ({
  id: r.id,
  routineId: r.routineId,
  occurrence: r.occurrence,
  // A run held at an approval step reads as waiting; its reason says on whom.
  status: r.status === 'paused' ? 'waiting' : r.status,
  reason: r.reason,
  threadId: r.threadId,
  startedAt: r.startedAt.toISOString(),
  finishedAt: iso(r.finishedAt),
  gate: r.gateDecision ? { decision: r.gateDecision, reason: r.gateReason ?? '' } : null,
});

