import { CheckInService } from './check-ins';
import { UnusedService } from './unused';
import { SubscriptionService } from './subscriptions';
import { ProviderKeyService } from './keys';
import { ModelCatalogService } from './model-catalog';
import { ImageService } from './images';
import { VideoService } from './videos';
import { TailscaleService } from './tailscale';
import { SkillService } from './skills';
import { ReactionNotifier } from './reactions';
import { RoomService } from './rooms';
import { SettingsService } from './settings';
import { ThreadService } from './threads';
import { UsageService } from './usage';
import { BotApi } from './bot-api';
import { VaultService } from './vault';
import { PasswordManagerService } from './password-managers';
import { PaymentCardService } from './payment-cards';
import { ContactDetailsService } from './contact-details';

export class Services {
  readonly access: AccessService;
  readonly bots: BotService;
  readonly threads: ThreadService;
  readonly rooms: RoomService;
  readonly approvals: ApprovalService;
  readonly actions: ActionService;
  readonly changes: TurnChangeService;
  readonly instructionDocs: InstructionDocService;
  readonly vault: VaultService;
  readonly passwordManagers: PasswordManagerService;
  readonly cards: PaymentCardService;
  readonly contacts: ContactDetailsService;
  readonly claudeAuth: ClaudeAuthService;
  readonly connections: ConnectionService;
  readonly memory: MemoryService;
  readonly memoryReview: MemoryReviewService;
  readonly memoryTidy: MemoryTidyService;
  readonly memoryFlags: MemoryFlagService;
  readonly promises: PromiseService;
  readonly routineSuggestions: RoutineSuggestionService;
  readonly skillSuggestions: SkillSuggestionService;
  readonly followUps: FollowUpService;
  readonly calls: CallService;
  readonly meetings: MeetingService;
  readonly push: PushService;
  readonly settings: SettingsService;
  readonly botImport: BotImportService;
  readonly keys: ProviderKeyService;
  readonly modelCatalog: ModelCatalogService;
  readonly images: ImageService;
  readonly videos: VideoService;
  readonly tailscale: TailscaleService;
  readonly skills: SkillService;
  readonly jobs: JobService;
  readonly routines: RoutineService;
  readonly rehearsals: RehearsalService;
  readonly routineHealth: RoutineHealthService;
  readonly checkIns: CheckInService;
  readonly unused: UnusedService;
  readonly subscriptions: SubscriptionService;
  readonly tools: ToolFactory;
  readonly turns: TurnManager;
  readonly reactions: ReactionNotifier;
  readonly usage: UsageService;
  readonly botApi: BotApi;
  readonly inbox: Inbox;
  readonly pageShares: PageShareService;
  readonly apiCredentials: ApiCredentialService;
  readonly canary: CanaryService;
  readonly email: EmailService;
  readonly ai: AiEndpointService;
  readonly embeddings: EmbeddingService;
  readonly transcribe: TranscribeService;
  readonly speech: SpeechService;
  readonly plugins: PluginService;
  readonly apiSources: ApiSourceService;
  readonly tickets: TicketService;
  readonly tables: TableService;
  readonly dashboards: DashboardService;
  readonly contentSeal: ContentSealService;
  readonly doctor: DoctorService;
  readonly titles: TitleService;
  readonly reviewer: ReviewerService;
  readonly offers: OfferService;
  /** Interactive cards bots show in conversations; `cards` are the vault's payment cards. */
  readonly chatCards: CardService;
  readonly linkPreviews = new LinkPreviews();
  readonly telegram: TelegramChannels;
  readonly whatsapp: WhatsAppChannel;
  readonly slack: SlackChannel;
  readonly discord: DiscordChannel;
  readonly teams: TeamsChannel;

  constructor(
    readonly ctx: Ctx,
    engineFor: (bot: Bot) => Engine,
    clock?: () => Date,
  ) {
    this.access = new AccessService(ctx);
    this.bots = new BotService(ctx);
    this.threads = new ThreadService(ctx);
    this.instructionDocs = new InstructionDocService(ctx, this.threads);
    this.rooms = new RoomService(ctx, this);
    this.vault = new VaultService(ctx);
    this.passwordManagers = new PasswordManagerService(ctx, this.vault);
    this.vault.useOthers(this.passwordManagers);
    this.cards = new PaymentCardService(ctx, this.vault);
    this.contacts = new ContactDetailsService(ctx, this.vault);
    this.claudeAuth = new ClaudeAuthService(ctx, this.vault);
    this.connections = new ConnectionService(ctx, this.vault);
    this.approvals = new ApprovalService(ctx, this.vault, this.threads);
    this.actions = new ActionService(ctx);
    this.changes = new TurnChangeService(ctx, this);
    this.memory = new MemoryService(ctx);
    this.push = new PushService(ctx, this.vault);
    this.settings = new SettingsService(ctx);
    this.botImport = new BotImportService(ctx, this.settings);
    this.subscriptions = new SubscriptionService(ctx, this.vault);
    this.modelCatalog = new ModelCatalogService(ctx, () => [
      ...this.keys.builtIn(),
      ...this.subscriptions.providers(),
    ]);
    this.keys = new ProviderKeyService(ctx, this.vault, fetch, this.subscriptions, this.modelCatalog);
    this.images = new ImageService(this.keys);
    this.videos = new VideoService(this.keys);
    this.tailscale = new TailscaleService(ctx.config.dataDir, ctx.config.port);
    this.skills = new SkillService(ctx);
    this.jobs = new JobService(ctx, this);
    this.routines = new RoutineService(ctx, this, engineFor, clock);
    this.tools = new ToolFactory(ctx, this, clock);
    this.turns = new TurnManager(ctx, this, engineFor);
    this.turns.onFinished((t, o) => this.jobs.onTurnFinished(t, o));
    this.turns.onFinished((t, o) => this.routines.onTurnFinished(t, o));
    this.rehearsals = new RehearsalService(ctx, this, clock);
    this.turns.onRehearsalFinished((t, o) => this.rehearsals.onTurnFinished(t, o));
    this.routineHealth = new RoutineHealthService(ctx, this, clock);
    this.unused = new UnusedService(ctx, this, clock);
    this.turns.onFinished((t, o) => this.rooms.onTurnFinished(t, o));
    this.reactions = new ReactionNotifier(ctx, this);
    this.usage = new UsageService(ctx, this.settings, clock);
    this.botApi = new BotApi(ctx, this);
    this.inbox = new Inbox(ctx, this);
    this.pageShares = new PageShareService(ctx);
    this.apiCredentials = new ApiCredentialService(ctx, this.vault);
    this.canary = new CanaryService(ctx, this);
    this.email = new EmailService(ctx, this);
    this.ai = new AiEndpointService(ctx, this.vault);
    this.embeddings = new EmbeddingService(ctx, this.ai);
    this.memory.useEmbeddings(this.embeddings);
    this.transcribe = new TranscribeService(this.keys, this.ai);
    this.speech = new SpeechService(this.ai);
    this.plugins = new PluginService(this);
    this.apiSources = new ApiSourceService(ctx, this.apiCredentials);
    this.tickets = new TicketService(ctx, this);
    this.tables = new TableService(ctx);
    this.contentSeal = new ContentSealService(ctx);
    this.doctor = new DoctorService(ctx, this);
    this.turns.onFinished((t, o) => this.tickets.onTurnFinished(t, o));
    this.memoryReview = new MemoryReviewService(ctx, this, engineFor);
    this.turns.onFinished((t, o) => this.memoryReview.onTurnFinished(t, o));
    this.memoryTidy = new MemoryTidyService(ctx, this, engineFor, clock);
    this.memoryFlags = new MemoryFlagService(ctx, this, clock);
    this.titles = new TitleService(ctx, this, engineFor);
    this.reviewer = new ReviewerService(ctx, this, engineFor);
    this.turns.onFinished((t, o) => this.titles.onTurnFinished(t, o));
    this.offers = new OfferService(ctx, this, engineFor, clock);
    this.chatCards = new CardService(ctx, this, clock);
    this.dashboards = new DashboardService(ctx, this, clock);
    this.turns.onFinished((t, o) => this.offers.onTurnFinished(t, o));
    this.threads.onContextReset((id) => this.memoryReview.onContextReset(id));
    this.promises = new PromiseService(ctx, this, engineFor, clock);
    this.turns.onFinished((t, o) => this.promises.onTurnFinished(t, o));
    this.routineSuggestions = new RoutineSuggestionService(ctx, this, engineFor, clock);
    this.skillSuggestions = new SkillSuggestionService(ctx, this, engineFor, clock);
    this.followUps = new FollowUpService(ctx, this, engineFor, clock);
    this.checkIns = new CheckInService(ctx, this, clock);
    this.calls = new CallService(ctx, this, clock);
    this.turns.onFinished((t, o) => this.followUps.onTurnFinished(t, o));
    this.meetings = new MeetingService(ctx, this, engineFor, clock);
    this.turns.onFinished((t) => this.meetings.onTurnFinished(t));
    this.telegram = new TelegramChannels(ctx, this, this.vault);
    this.whatsapp = new WhatsAppChannel(ctx, this, this.vault);
    this.turns.onFinished((t, o) => this.whatsapp.onTurnFinished(t, o));
    this.slack = new SlackChannel(ctx, this, this.vault);
    this.discord = new DiscordChannel(ctx, this, this.vault);
    this.teams = new TeamsChannel(ctx, this, this.vault);
  }
}
